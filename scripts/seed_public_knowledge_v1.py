def main() -> None:
    db = SessionLocal()
    created = 0
    skipped = 0
    try:
        for item in CONTENT:
            if db.query(PublicContent).filter(PublicContent.slug == item["slug"]).first():
                skipped += 1
                continue
            db.add(PublicContent(
                content_type="article",
                status="draft",
                source_type="medical-education",
                created_by="system-seed-knowledge-v1",
                **item,
            ))
            created += 1
        db.commit()
        print(f"created={created} skipped={skipped} total={db.query(PublicContent).count()}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
