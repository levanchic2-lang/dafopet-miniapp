def main() -> None:
    db = SessionLocal()
    created = 0
    updated = 0
    try:
        for item in CONTENT:
            row = db.query(PublicContent).filter(PublicContent.slug == item["slug"]).first()
            if not row:
                db.add(PublicContent(**item, status="draft", created_by="system-seed-v1"))
                created += 1
                continue
            untouched = (
                row.status == "draft"
                and row.created_by in ("system-seed", "system-seed-v1")
                and "待医生根据医院当前实际流程补充并审核" in (row.body or "")
            )
            if untouched:
                row.content_type = item["content_type"]
                row.title = item["title"]
                row.summary = item["summary"]
                row.body = item["body"]
                updated += 1
        db.commit()
        print(f"created={created} updated={updated} total={db.query(PublicContent).count()}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
